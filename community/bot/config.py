"""
config.py — AI一次対応bot の設定（ここだけ触れば運用を変えられる）。

今後の変更ポイントは基本ここ：
  - 応答するチャンネル名／モデル／トーン／安全ルール／エスカレーション文
  - 講座の中身・FAQは knowledge/*.md を編集（コードは触らない）
"""

# ===== 応答するチャンネル =====
# このチャンネル名（の一部）を含むチャンネルで、メッセージに自動応答する。
# どのチャンネルでも @AIサポート とメンションされたら応答する（下の設定に関わらず）。
AUTO_REPLY_CHANNELS = ["質問ひろば", "質問"]   # 部分一致

# ===== 「待ってから出る」（2026/8/4・桜木さん指定） =====
#
# botが即答すると、認定講師と仲間が話す前に会話が終わる。
# 特典③は「認定講師が、並んで歩きます」なので、**人が先**でないと特典が成立しない。
#
# なので、呼ばれていないときは**しばらく待ち、誰も答えなかったときだけ**出る。
# 栞のメールにある「必ず誰かがお返事します」は、この形でも守られる。
#   人が答えれば、それが「誰か」。誰も答えなければ、botが出る。無視は起きない。
# ⚠️ 2026-08-20：認定講師の稼働がまだ0件のため、15分→5分に短縮。
#    15分待っても人が答えないなら、それは「返事が15分遅い」だけになる。
#    講師の稼働が立ち上がったら、15分に戻すこと。
# ⚠️ 待ち時間の考え方（2026-08-24 見直し）
#
#    「人が先に答える機会を残す」ために待つ。ただし**場所によって重みが違う**。
#
#    ・#質問ひろば … 本物の質問。**仲間の答えのほうが価値がある**ことが多い。
#      　　　　　　　だから、ここは待つ意味がある。
#    ・#今週の栞  … 返すのは「次の一手」。**bot主導で設計している**。
#      　　　　　　　しかも朝7時に書く方が多く、30分後には出かけている。
#      　　　　　　　待つほど、その日のうちに動けなくなる。
#
#    以前は 栞30分 ／ 質問5分 と、**逆になっていた**。栞を短くする。
#
#    ⚠️ ゼロにはしない。数秒で返すと、明らかに自動返信に見える。
#    　 2〜3分あると「見て、書いてくれた」に見える。ここは体感の問題。
WAIT_MIN_QUESTION = 5       # 質問ひろば：何分待つか（週番が始まったら15分に戻す）
WAIT_MIN_SHIORI = 3         # 今週の栞：何分待つか

# 夜中は待たない。一人で困っている人を、朝まで放置しないため。
NIGHT_FROM = 22             # この時刻から
NIGHT_TO = 8                # この時刻まで（翌朝）は即答

# 短い相づちには反応しない。「ありがとう」「おはよう」に毎回返すと、うるさい。
#
# ⚠️ 2026-08-20：10文字は**長すぎた**。
#    「どこですか？」（6文字）「できました！」（6文字）「これで合ってますか」（9文字）
#    ——いちばん助けが要る短い追い質問が、全部こぼれていた。
#    文脈を見るようになったので、短くても意味が取れる。6文字に下げる。
MIN_LEN_TO_ANSWER = 6

# ⚠️ ただし、これだけの言葉なら答えない（あいさつ・相づち）
IGNORE_EXACT = [
    "ありがとうございます", "ありがとう", "ありがとうございました",
    "おはようございます", "おはよう", "こんにちは", "こんばんは",
    "おつかれさまです", "了解です", "承知しました", "はい", "わかりました",
    "がんばります", "うれしいです", "すごい", "なるほど",
]

# 暴走したときの保険。1日にこのチャンネルで話す上限
DAILY_LIMIT_PER_CHANNEL = 20

# ===== モデル =====
# ChatGPT（OpenAI）を使う。キーは .env の OPENAI_API_KEY。
# 既定は gpt-5.4-mini＝小さくて安いモデル。この用途（短い一次対応）には十分。
# もっと安く：gpt-5.4-nano ／ もっと賢く：gpt-5.4
MODEL = "gpt-5.4-mini"
# ⚠️ 2026-08-24：500 → 1200 に戻しました。
#    栞の返事のプロンプトに「全体像の地図」を足したところ、
#    考える枠でトークンを使い切り、**本文が空**になって
#    エスカレーション文（「お答えできませんでした」）が返る事故が起きました。
#    短さは MAX_TOKENS ではなく、**プロンプトの「4〜5行」指定**で担保します。
MAX_TOKENS = 1200
REASONING = "low"         # 考え込ませない。一次対応で長考は要らないし、遅く・高くなる

# ===== bot の人格・トーン =====
PERSONA = """あなたは「らくらくAIキャンパス」の、やさしいAIサポート係です。
受講生は40〜60代の女性が中心で、AIやパソコンが得意でない方も多くいます。
次の姿勢で答えてください：
- とても やさしく、あたたかく、共感を込めて。専門用語・横文字は避け、かみくだいて説明する。
- **とにかく短く。3〜5行で終える。** 長い前置きはしない。
- 一度に全部教えようとしない。**まず1歩だけ**伝えて、「やってみて、また教えてください」で受ける。
- 講座の場所を案内するときは、**部屋の名前とレッスン名を、そのまま**伝える。
  例：「収入の種の部屋の『M2-2 無料で、写真を動かす』にあります」
- 「こんな初歩的なこと聞いていいの？」という不安に、いつも「大歓迎です」と応える。
- スマホでの操作を前提に、具体的な手順で。
- 断定や約束はしない（「必ず稼げる」「必ず叶う」等は言わない）。
- 分からないこと・キャンパスの範囲外は、正直に「分かりません」と言い、下記のエスカレーションへ。
"""

# ===== 応答の姿勢（重い相談の扱い方） =====
SAFETY = """【健康・医療／お金・投資／法律・税金 などの重い相談の扱い】
- 具体的な助言・診断・投資判断・法的判断はしない。
- 肯定も否定もしない。相手の気持ちは、あたたかく受け止めつつ、断定を避け、会話をやわらかく流す。
- 「専門家へ相談してください」と説教くさく突き放さない。誘導するとしても、あくまで自然な会話の中で、そっと。
- AIにできる範囲（気持ちの整理を手伝う・一般的な話をやさしく言いかえる・調べ方のヒント）にとどめ、最終判断は相手にゆだねる。
- どうしても答えにくい時は、無理をせず、下記のエスカレーション文を返す。

【bot自身のふるまい（受講生に注意や説教はしない）】
- 自分からは、収入や成果を「必ず〇〇できる」と約束する言い方はしない。
- 個人情報や収入保証について、こちらから明示的に注意・警告はしない（自然に振る舞う）。
"""

